import { iso6393 } from 'iso-639-3'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outFile = resolve(root, 'src/data/languages.ts')

// Languages used by courses that have no ISO 639-1 code.
const EXTRA_LANGUAGE_CODES = new Set(['lfn'])

const languages = iso6393
  .filter(
    (language) =>
      language.iso6391 || EXTRA_LANGUAGE_CODES.has(language.iso6393),
  )
  .map((language) => ({
    code: language.iso6393,
    iso6391: language.iso6391 ?? '',
    name: language.name,
  }))
  .sort((a, b) => a.name.localeCompare(b.name, 'en'))

const body = `// Generated by scripts/generate-languages.mjs. Do not edit by hand.
// ISO 639-3 languages that also have an ISO 639-1 code, plus selected
// languages used by courses (for example constructed languages such as lfn).

export interface Language {
  code: string
  iso6391: string
  name: string
}

export const LANGUAGES: readonly Language[] = ${JSON.stringify(languages, null, 2)} as const

export const LANGUAGE_BY_CODE: ReadonlyMap<string, Language> = new Map(
  LANGUAGES.map((language) => [language.code, language]),
)

export function languageName(code: string): string {
  return LANGUAGE_BY_CODE.get(code)?.name ?? code
}

export function languageLabel(code: string): string {
  const language = LANGUAGE_BY_CODE.get(code)
  return language ? \`\${language.name} (\${code})\` : code
}

export function isKnownLanguage(code: string): boolean {
  return LANGUAGE_BY_CODE.has(code)
}

export function searchLanguages(query: string, limit = 60): Language[] {
  const needle = query.trim().toLowerCase()
  if (!needle) return LANGUAGES.slice(0, limit)

  const startsWith: Language[] = []
  const contains: Language[] = []

  for (const language of LANGUAGES) {
    const name = language.name.toLowerCase()
    if (name.startsWith(needle) || language.code.startsWith(needle)) {
      startsWith.push(language)
    } else if (name.includes(needle)) {
      contains.push(language)
    }
    if (startsWith.length >= limit) break
  }

  return [...startsWith, ...contains].slice(0, limit)
}

export const DEFAULT_TARGET_LANGUAGE = 'swe'
export const DEFAULT_INSTRUCTION_LANGUAGE = 'eng'
`

await mkdir(dirname(outFile), { recursive: true })
await writeFile(outFile, body, 'utf8')
console.log(`Wrote ${languages.length} languages to ${outFile}`)
